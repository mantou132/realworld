import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: '/Applications/Google Chrome Canary.app/Contents/MacOS/Google Chrome Canary' });
const p = await b.newPage();
p.on('console', (m) => ['error', 'warning'].includes(m.type()) && console.log(m.type(), m.text().slice(0, 300)));
p.on('pageerror', (e) => console.log('pageerror', e.message));
p.on('response', (r) => ['POST', 'DELETE'].includes(r.request().method()) && console.log(r.request().method(), r.status(), r.url()));
const base = process.argv[2];
const u = `probe${Date.now()}`;
await p.goto(base + '/register');
await p.fill('input[name=username]', u); await p.fill('input[name=email]', u + '@x.com'); await p.fill('input[name=password]', 'password123');
await p.click('button[type=submit]'); await p.waitForURL(base + '/');
await p.goto(base + '/', { waitUntil: 'load' });
const href = await p.locator('.preview-link').first().getAttribute('href');
await p.goto(base + href, { waitUntil: 'load' });
await p.click('button.btn-outline-primary:has-text("Favorite") >> nth=0'); await p.waitForTimeout(1500);
console.log('fav:', await p.locator('.article-meta button').allInnerTexts());
await p.fill('textarea[placeholder="Write a comment..."]', 'Comment to be deleted'); await p.click('button:has-text("Post Comment")'); await p.waitForTimeout(800);
await p.locator('.card').filter({ hasText: 'Comment to be deleted' }).locator('span.mod-options i.ion-trash-a').click(); await p.waitForTimeout(1000);
console.log('comment still there:', await p.locator('.card-block:has-text("Comment to be deleted")').count());
await b.close();
